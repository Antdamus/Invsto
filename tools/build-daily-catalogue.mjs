// Public representative shell on the existing branded storefront. Staff tools
// remain in Invsto; both views use the same gallery and catalogue renderer.
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const source=await readFile(new URL('inventory-daily-catalogue.html',root),'utf8');
const output='<!-- Generated by tools/build-daily-catalogue.mjs. -->\n'+source
 .replace('<body class="daily-catalogue">','<body class="daily-catalogue" data-catalogue-audience="public">')
 .replace(/ <section id="staff-panel"[\s\S]*?\n <\/section>\r?\n/,'')
 .replace(/<a id="back-catalogues"[^>]*>[\s\S]*?<\/a>/,'')
 .replace(/(href|src)="((?:catalogue[^"/]*|inventory-daily-catalogue\.(?:css|js))\?[^" ]+)"/g,'$1="https://antdamus.github.io/Invsto/$2"');
if(output.includes('id="staff-panel"')||output.includes('id="back-catalogues"'))throw new Error('Staff controls must not appear in the public shell');
await writeFile(new URL('StoreWebsite/representative-catalogue.html',root),output);
