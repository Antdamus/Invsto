// The branded storefront serves StoreWebsite as its root. Keep its client-only
// shell synchronized with the source; shared assets are versioned on Pages.
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const source=await readFile(new URL('catalogue.html',root),'utf8');
const output='<!-- Generated by tools/build-client-catalogue.mjs from catalogue.html. -->\n'+source
 .replaceAll('href="catalogue.css?', 'href="https://antdamus.github.io/Invsto/catalogue.css?')
 .replaceAll('src="catalogue-core.js?', 'src="https://antdamus.github.io/Invsto/catalogue-core.js?')
 .replaceAll('src="catalogue-client.js?', 'src="https://antdamus.github.io/Invsto/catalogue-client.js?');
await writeFile(new URL('StoreWebsite/private-catalogue.html',root),output);
